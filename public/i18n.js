// Current language table: built-in, saved AI translation, or English while it loads.
let currentStrings = STRINGS.en;

// tr("askSend", { who: "Shad" }) -> text in the current language
function tr(key, vars = {}) {
  const text = currentStrings[key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}

// Load the table for a language code like "mr-IN". Returns true when the screen should re-render.
async function loadStrings(langCode, onStart) {
  const base = langCode.split("-")[0];
  if (STRINGS[base]) { currentStrings = STRINGS[base]; return true; }
  let cached = null;
  try { cached = JSON.parse(localStorage.getItem("bolo.i18n." + base) || "null"); } catch { /* storage blocked */ }
  if (cached && Object.keys(STRINGS.en).every((k) => k in cached)) { currentStrings = cached; return true; }
  currentStrings = STRINGS.en;
  onStart && onStart();
  try {
    const res = await fetch("/api/translate", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ lang: langCode, strings: STRINGS.en }),
    });
    const data = await res.json();
    if (!res.ok) throw new Error(data.error || res.statusText);
    currentStrings = { ...STRINGS.en, ...data };
    try { localStorage.setItem("bolo.i18n." + base, JSON.stringify(currentStrings)); } catch { /* storage blocked */ }
    return true;
  } catch {
    return false;
  }
}

// Apply translations to every element marked in index.html.
function applyStaticStrings() {
  document.querySelectorAll("[data-i18n]").forEach((n) => (n.textContent = tr(n.dataset.i18n)));
  document.querySelectorAll("[data-i18n-ph]").forEach((n) => (n.placeholder = tr(n.dataset.i18nPh)));
  document.querySelectorAll("[data-i18n-title]").forEach((n) => (n.title = tr(n.dataset.i18nTitle)));
}
